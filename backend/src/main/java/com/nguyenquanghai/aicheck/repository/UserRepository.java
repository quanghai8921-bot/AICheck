package com.nguyenquanghai.aicheck.repository;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

import com.nguyenquanghai.aicheck.entity.Quser;
import com.nguyenquanghai.aicheck.entity.user;
import com.querydsl.core.BooleanBuilder;
import com.querydsl.jpa.impl.JPAQueryFactory;

import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;

@Repository
@RequiredArgsConstructor
public class UserRepository {

    private final JPAQueryFactory queryFactory;
    private final EntityManager entityManager;

    private final Quser qUser = Quser.user;

    /**
     * Persists a new user. The caller must supply a password hash and an
     * existing role; userId and createdAt are generated by the entity.
     */
    @Transactional
    public user create(user user) {
        if (user == null) {
            throw new IllegalArgumentException("Thông tin user không được để trống.");
        }

        if (user.getUserId() != null) {
            throw new IllegalArgumentException("User mới không được có userId.");
        }

        entityManager.persist(user);
        return user;
    }

    /** Finds one user by its primary key. */
    public Optional<user> findById(UUID userId) {
        if (userId == null) {
            return Optional.empty();
        }

        return Optional.ofNullable(
                queryFactory
                        .selectFrom(qUser)
                        .where(qUser.userId.eq(userId))
                        .fetchOne());
    }

    /** Finds one user by email. Email is treated as the login identifier. */
    public Optional<user> findByEmail(String email) {
        if (email == null || email.isBlank()) {
            return Optional.empty();
        }

        return Optional.ofNullable(
                queryFactory
                        .selectFrom(qUser)
                        .where(qUser.email.equalsIgnoreCase(email.trim()))
                        .fetchOne());
    }

    public Optional<user> findForLogin(String email) {
        return findByEmail(email);
    }

    public List<user> search(
            String keyword,
            String status,
            long offset,
            long limit) {

        BooleanBuilder condition = new BooleanBuilder();

        if (keyword != null && !keyword.isBlank()) {
            String normalizedKeyword = keyword.trim();
            condition.and(
                    qUser.fullName.containsIgnoreCase(normalizedKeyword)
                            .or(qUser.email.containsIgnoreCase(normalizedKeyword))
                            .or(qUser.phoneNumber.contains(normalizedKeyword))
                            .or(qUser.identificationCard.contains(normalizedKeyword)));
        }

        if (status != null && !status.isBlank()) {
            condition.and(qUser.status.equalsIgnoreCase(status.trim()));
        }

        return queryFactory
                .selectFrom(qUser)
                .where(condition)
                .orderBy(qUser.createdAt.desc(), qUser.fullName.asc())
                .offset(Math.max(offset, 0))
                .limit(Math.max(limit, 1))
                .fetch();
    }

    public long count(String keyword, String status) {
        BooleanBuilder condition = buildSearchCondition(keyword, status);

        Long result = queryFactory
                .select(qUser.count())
                .from(qUser)
                .where(condition)
                .fetchOne();

        return result == null ? 0L : result;
    }

    public boolean existsDuplicate(
            String email,
            String phoneNumber,
            String identificationCard,
            UUID excludedUserId) {

        BooleanBuilder duplicate = new BooleanBuilder();

        if (email != null && !email.isBlank()) {
            duplicate.or(qUser.email.equalsIgnoreCase(email.trim()));
        }
        if (phoneNumber != null && !phoneNumber.isBlank()) {
            duplicate.or(qUser.phoneNumber.eq(phoneNumber.trim()));
        }
        if (identificationCard != null && !identificationCard.isBlank()) {
            duplicate.or(qUser.identificationCard.eq(identificationCard.trim()));
        }

        if (!duplicate.hasValue()) {
            return false;
        }

        if (excludedUserId != null) {
            duplicate.and(qUser.userId.ne(excludedUserId));
        }

        return queryFactory
                .selectOne()
                .from(qUser)
                .where(duplicate)
                .fetchFirst() != null;
    }

    @Transactional
    public boolean updateProfile(
            UUID userId,
            String fullName,
            LocalDateTime dateOfBirth,
            String phoneNumber,
            String email,
            String sex,
            String identificationCard,
            String address) {

        return queryFactory
                .update(qUser)
                .set(qUser.fullName, fullName)
                .set(qUser.dateOfBirth, dateOfBirth)
                .set(qUser.phoneNumber, phoneNumber)
                .set(qUser.email, email)
                .set(qUser.sex, sex)
                .set(qUser.identificationCard, identificationCard)
                .set(qUser.address, address)
                .where(qUser.userId.eq(userId))
                .execute() == 1;
    }

    @Transactional
    public boolean updatePassword(UUID userId, String passwordHash) {
        return queryFactory
                .update(qUser)
                .set(qUser.passwords, passwordHash)
                .where(qUser.userId.eq(userId))
                .execute() == 1;
    }

    @Transactional
    public boolean updateStatus(UUID userId, String status) {
        return queryFactory
                .update(qUser)
                .set(qUser.status, status)
                .where(qUser.userId.eq(userId))
                .execute() == 1;
    }

    private BooleanBuilder buildSearchCondition(String keyword, String status) {
        BooleanBuilder condition = new BooleanBuilder();

        if (keyword != null && !keyword.isBlank()) {
            String normalizedKeyword = keyword.trim();
            condition.and(
                    qUser.fullName.containsIgnoreCase(normalizedKeyword)
                            .or(qUser.email.containsIgnoreCase(normalizedKeyword))
                            .or(qUser.phoneNumber.contains(normalizedKeyword))
                            .or(qUser.identificationCard.contains(normalizedKeyword)));
        }

        if (status != null && !status.isBlank()) {
            condition.and(qUser.status.equalsIgnoreCase(status.trim()));
        }

        return condition;
    }
}
